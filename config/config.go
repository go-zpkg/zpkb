// Package config computes the on-disk workspace layout for a build. The build
// tree is keyed on the *target* platform+arch so a cross build (eg. Windows)
// gets its own directories and never collides with a native build of the same
// package.
package config

import (
	"os"
	"path/filepath"
	"runtime"
	"strings"

	"github.com/go-zpkg/zpkb/target"
)

// userHomeDir is a seam so tests can exercise the no-home fallback paths.
var userHomeDir = os.UserHomeDir

// buildTreeDir is the directory under the XDG data home that holds every
// build's home, sources, build and testbed.
//
// ⛔⛔ IT WAS `brewkit`, AND NO FALLBACK IS READ. The owner's decision of
// 2026-11-15: we do not share with a tool we no longer support, and we are
// sovereign over our own naming. `~/.local/share/brewkit` is upstream
// brewkit's build tree; ours sitting in the same directory was the exact
// collision the binary rename existed to remove — `target.go` makes that
// argument to refuse `BREWKIT_TARGET`, with a gate, and the directory was
// simply missed when the variable was done.
//
// ⚠ IT IS A BREAKING CHANGE AND A CHEAP ONE, and the difference matters: this
// tree is a CACHE. Everything under it — homes, srcs, builds, testbeds — is
// regenerated by the next build, so an orphaned `~/.local/share/brewkit` costs
// a rebuild and loses nothing. A tarball cache is the only thing re-downloaded.
// That is why no migration is offered: a migration would copy a cache, and an
// alias would leave two trees that disagree about which build is current.
//
// ⛔ A reader looking for the old tree will not find it mentioned anywhere else,
// so it is named HERE and nowhere else, and `TestTheOldBuildTreeIsNotUsed` is
// the gate — because "we stopped using it" is a claim about code that nothing
// was asserting.
const buildTreeDir = "zpkb"

// Paths is the set of directories a build uses.
type Paths struct {
	// Root is the directory every other build directory lives under (our build
	// tree under the data home, or the pantry checkout). It is what -ffile-prefix-map maps to
	// /build, so no builder path leaks into an artifact (go-zpkg/bk#387).
	Root         string
	Home         string // a fresh HOME for the build (== bkroot for the default layout)
	Src          string // extracted sources
	Build        string // where the build runs
	Test         string // where tests stage and run
	TarballDir   string // where downloaded source tarballs are cached
	Install      string // final install prefix: $ZPKG_DIR/<project>/v<version>
	BuildInstall string // staging prefix the build writes to: <Install>+builddir
}

// ZpkgDir returns the store prefix ($ZPKG_DIR, else ~/.zpkg).
//
// ⛔⛔ IT MUST AGREE WITH artifact.Dir(), AND FOR A WHILE IT DID NOT. This
// returned `~/.pkgx` long after artifact/pkgx.go:385 moved the store to
// `~/.zpkg`, so one product had two functions computing the store root and
// they disagreed — zpkb staged and looked in upstream pkgx's directory while
// everything built on artifact used ours. The duplication is the defect; this
// is the cheap half of the fix and the two should become one call.
func ZpkgDir() string {
	if d := os.Getenv("ZPKG_DIR"); d != "" {
		return d
	}
	home, err := userHomeDir()
	if err != nil {
		return ".zpkg"
	}
	return filepath.Join(home, ".zpkg")
}

// dataHome is the XDG data home ($XDG_DATA_HOME, else ~/.local/share; on macOS
// ~/Library/Caches — see dataHomeFor for why that and not "Application
// Support"). It is the XDG location for a build tree; which DIRECTORY we take
// inside it is `buildTreeDir`, and it is ours.
func dataHome() string {
	if d := os.Getenv("XDG_DATA_HOME"); d != "" {
		return d
	}
	home, err := userHomeDir()
	if err != nil {
		return filepath.Join(".local", "share")
	}
	return dataHomeFor(runtime.GOOS, home)
}

// dataHomeFor is the pure, testable OS split of dataHome. On darwin it uses
// ~/Library/Caches rather than "Application Support": the build tree lives here
// and that path has NO space — autotools/libtool choke on spaces in build paths
// even when quoted, and "Application Support" would poison every macOS build.
func dataHomeFor(goos, home string) string {
	if goos == "darwin" {
		return filepath.Join(home, "Library", "Caches")
	}
	return filepath.Join(home, ".local", "share")
}

// Compute lays out the build directories for project@version built for tgt.
//
// When ZPKG_RECIPE_DIR is set, the workspace is rooted under that checkout
// (homes/srcs/builds/testbeds), matching brewkit's in-tree layout; otherwise it
// lives under the XDG data home, keyed on the target platform+arch.
//
// ⛔ THERE IS NO SECOND SPELLING ANY MORE. This used to read ZPKG_PANTRY_DIR
// "or the older ZPKG_PANTRY_PATH", and two spellings of one thing is the state
// target.go argues against: every document has to explain both forever, and a
// caller setting the one that lost is silently ignored. Both retired together
// with the rest of the `pantry` vocabulary; `retiredEnv` refuses either by name.
// ⛔⛔ `hash` IS THE BUILD'S IDENTITY AND IT GOES IN THE INSTALL PREFIX. The
// prefix is baked into every binary the build produces — an `@rpath`-relative
// reference like `@rpath/zlib.net/v1.3.2/lib/libz.1.dylib`, read out of a
// real published artifact — so a prefix that names only the version produces
// binaries that cannot say WHICH build they were linked against, and a store
// that cannot hold two builds of one version.
//
// With the hash in it the artifact stays relocatable AND names itself, which is
// the combination Nix gives up (its paths are absolute) and Spack gives up
// (its paths are not designed to move). See go-zpkg/zpkb#410.
//
// An empty hash is not accepted: a caller that does not know the identity
// has not resolved the closure yet, and the prefix must not be chosen before
// it has.
func Compute(project, version, hash string, tgt target.Target) Paths {
	if hash == "" {
		panic("config: Compute with no build identity — the prefix would not name which build it is")
	}
	install := filepath.Join(ZpkgDir(), filepath.FromSlash(project), "v"+version+"-h"+hash)
	p := Paths{
		Install:      install,
		BuildInstall: install + "+builddir",
	}

	if checkout := recipeCheckout(); checkout != "" {
		p.Root = checkout
		slug := strings.ReplaceAll(project, "/", "__")
		spec := slug + "-" + version
		p.Home = filepath.Join(checkout, "homes", spec)
		p.Src = filepath.Join(checkout, "srcs", spec)
		p.Build = filepath.Join(checkout, "builds", spec)
		p.Test = filepath.Join(checkout, "testbeds", spec)
		p.TarballDir = filepath.Join(checkout, "srcs")
		return p
	}

	dh := filepath.Join(dataHome(), buildTreeDir)
	// OSDir, so that a glibc and a musl build of the same project at the same
	// version do not share a source tree, a build directory and a testbed. The
	// separator stays "+" — this is a directory NAME, not a path — and an
	// unnamed libc spells what it spelled before, so no existing build tree
	// is orphaned.
	root := filepath.Join(dh, tgt.OSDir()+"+"+tgt.Arch, filepath.FromSlash(project), "v"+version)
	p.Root = dh
	p.Home = root
	p.Src = filepath.Join(root, "src")
	p.Build = filepath.Join(root, "build")
	p.Test = filepath.Join(root, "testbed")
	p.TarballDir = dh
	return p
}

func recipeCheckout() string {
	return os.Getenv("ZPKG_RECIPE_DIR")
}
